package com.example.labo.engine

import com.example.labo.model.LogLevel
import java.io.File

data class FsConfigEntry(
    val path: String,
    val uid: Int,
    val gid: Int,
    val mode: String,
    val capabilities: String = "0x0"
)

data class FileContextEntry(
    val pattern: String,
    val context: String
)

class FilesystemEngine(
    private val coreEngine: CoreEngine
) : BaseEngine {
    override val name: String = "FilesystemEngine"
    override val description: String = "Moteur spécialisé dans la gestion, analyse et configuration des systèmes de fichiers et permissions"
    override val isReady: Boolean = true

    init {
        coreEngine.registerEngine(this)
    }

    fun parseFsConfig(fsConfigFile: File): List<FsConfigEntry> {
        if (!fsConfigFile.exists()) return emptyList()
        val list = mutableListOf<FsConfigEntry>()
        runCatching {
            fsConfigFile.forEachLine { line ->
                val trimmed = line.trim()
                if (trimmed.isNotEmpty() && !trimmed.startsWith("#")) {
                    val parts = trimmed.split("\\s+".toRegex())
                    if (parts.size >= 4) {
                        val path = parts[0]
                        val uid = parts[1].toIntOrNull() ?: 0
                        val gid = parts[2].toIntOrNull() ?: 0
                        val mode = parts[3]
                        val caps = if (parts.size >= 5) parts[4] else "0x0"
                        list.add(FsConfigEntry(path, uid, gid, mode, caps))
                    }
                }
            }
        }.onFailure {
            coreEngine.log(LogLevel.ERROR, name, "Erreur parsing fs_config : ${it.message}")
        }
        return list
    }

    fun generateFsConfigFile(entries: List<FsConfigEntry>, outputFile: File) {
        outputFile.parentFile?.mkdirs()
        outputFile.bufferedWriter().use { writer ->
            writer.write("# fs_config generated by LABO FilesystemEngine\n")
            entries.forEach { entry ->
                writer.write("${entry.path} ${entry.uid} ${entry.gid} ${entry.mode} ${entry.capabilities}\n")
            }
        }
        coreEngine.log(LogLevel.DEBUG, name, "Fichier fs_config généré (${entries.size} entrées) : ${outputFile.name}")
    }

    fun parseFileContexts(fileContextsFile: File): List<FileContextEntry> {
        if (!fileContextsFile.exists()) return emptyList()
        val list = mutableListOf<FileContextEntry>()
        runCatching {
            fileContextsFile.forEachLine { line ->
                val trimmed = line.trim()
                if (trimmed.isNotEmpty() && !trimmed.startsWith("#")) {
                    val parts = trimmed.split("\\s+".toRegex())
                    if (parts.size >= 2) {
                        val pattern = parts[0]
                        val context = parts.last()
                        list.add(FileContextEntry(pattern, context))
                    }
                }
            }
        }.onFailure {
            coreEngine.log(LogLevel.ERROR, name, "Erreur parsing file_contexts : ${it.message}")
        }
        return list
    }

    fun generateFileContextsFile(entries: List<FileContextEntry>, outputFile: File) {
        outputFile.parentFile?.mkdirs()
        outputFile.bufferedWriter().use { writer ->
            writer.write("# file_contexts generated by LABO FilesystemEngine\n")
            entries.forEach { entry ->
                writer.write("${entry.pattern.padEnd(45)} ${entry.context}\n")
            }
        }
        coreEngine.log(LogLevel.DEBUG, name, "Fichier file_contexts généré (${entries.size} entrées) : ${outputFile.name}")
    }

    fun inferBootableFsConfig(relativePath: String, isDirectory: Boolean): FsConfigEntry {
        val normalized = if (relativePath.startsWith("/")) relativePath else "/$relativePath"

        return when {
            // Binaries & Shell commands (root/shell execution)
            normalized.startsWith("/system/bin") || normalized.startsWith("/system/xbin") -> {
                if (isDirectory) FsConfigEntry(normalized, 0, 2000, "0755")
                else FsConfigEntry(normalized, 0, 2000, "0755")
            }
            // System APK applications
            normalized.startsWith("/system/app") || normalized.startsWith("/system/priv-app") -> {
                if (isDirectory) FsConfigEntry(normalized, 0, 0, "0755")
                else FsConfigEntry(normalized, 0, 0, "0644")
            }
            // Framework and libraries
            normalized.startsWith("/system/framework") || normalized.startsWith("/system/lib") -> {
                if (isDirectory) FsConfigEntry(normalized, 0, 0, "0755")
                else FsConfigEntry(normalized, 0, 0, "0644")
            }
            // System Configurations & Permissions
            normalized.startsWith("/system/etc") -> {
                if (isDirectory) FsConfigEntry(normalized, 0, 0, "0755")
                else FsConfigEntry(normalized, 0, 0, "0644")
            }
            // Root directories
            isDirectory -> FsConfigEntry(normalized, 0, 0, "0755")
            else -> FsConfigEntry(normalized, 0, 0, "0644")
        }
    }

    fun inferSelinuxContext(relativePath: String): String {
        val normalized = if (relativePath.startsWith("/")) relativePath else "/$relativePath"
        return when {
            normalized.startsWith("/system/bin") || normalized.startsWith("/system/xbin") -> "u:object_r:system_file:s0"
            normalized.startsWith("/system/app") || normalized.startsWith("/system/priv-app") -> "u:object_r:system_file:s0"
            normalized.startsWith("/system/etc/selinux") -> "u:object_r:sepolicy_file:s0"
            normalized.startsWith("/system/etc") -> "u:object_r:system_file:s0"
            normalized.contains("build.prop") -> "u:object_r:system_file:s0"
            else -> "u:object_r:system_file:s0"
        }
    }
}
